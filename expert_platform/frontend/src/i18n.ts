export type Locale = 'zh-CN' | 'en-US'

const savedLocale = localStorage.getItem(STORAGE_KEY)
const locale = ref<Locale>(savedLocale === 'en-US' ? 'en-US' : 'zh-CN')

function applyLocale(nextLocale: Locale) {
  locale.value = nextLocale
  localStorage.setItem(STORAGE_KEY, nextLocale)
  document.documentElement.lang = nextLocale
  document.title = nextLocale === 'zh-CN' ? zhCN['common.productName'] : enUS['common.productName']
}

function t(key: TranslationKey, params: Record<string, string | number> = {}) {
  const messages = locale.value === 'zh-CN' ? zhCN : enUS
  return Object.entries(params).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[key] as string,
  )
}

export const translate = t

applyLocale(locale.value)

export function useI18n() {
  return {
    locale,
    localeTag: computed(() => locale.value),
    setLocale: applyLocale,
    t,
    expertName: (expert: { id: string; name: string }) => {
      if (expert.id === '__all__') return t('experts.all')
      if (expert.id === 'default') return t('experts.shared')
      return expert.name
    },
  }
}
